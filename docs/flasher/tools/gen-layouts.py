#!/usr/bin/env python3
"""Generate js/layouts.js from the per-variant rawprogram XMLs.

The flasher never writes at offsets taken from these tables. It writes at the
offsets in the phone's own GPT, and uses these tables only to recognise which
variant's partition layout it is looking at and to refuse anything else.

Usage: tools/gen-layouts.py <flash-staging dir> > js/layouts.js
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

VARIANTS = {"pvg100": "rawprogram0.pvg100.xml", "pvg100e": "rawprogram0.pvg100e.xml"}


def layout(path):
    parts = []
    for p in ET.parse(path).getroot().iter("program"):
        label = p.get("label")
        if label in ("PrimaryGPT", "BackupGPT"):
            continue
        parts.append([label, int(p.get("start_sector")), int(p.get("num_partition_sectors"))])
    return parts


def main():
    staging = Path(sys.argv[1])
    out = {v: layout(staging / f) for v, f in VARIANTS.items()}
    print("// GENERATED by tools/gen-layouts.py from rawprogram0.<variant>.xml. Do not edit.")
    print("// Each entry: [label, start_sector, num_sectors], 512-byte sectors.")
    print("export const LAYOUTS = {")
    for v, parts in out.items():
        print(f"  {v}: [")
        for p in parts:
            print(f"    {json.dumps(p)},")
        print("  ],")
    print("};")


if __name__ == "__main__":
    main()
